  --0000_0000_0000_0_0_0000_00000000
  --ALU___TB___FB__S_PC_SEQ_uAddr
  (
    -- Hämtfas
    b"0000_0011_1101_0_0_0000_00000000", -- ASR:=PC 00 uPC++
    b"0000_0010_0001_0_1_0000_00000000", -- IR:=PM, PC:=PC+1
    b"0000_0000_0000_0_0_0010_00000000", -- uPC:= K2
    
    -- Adresseringsmoder
    b"0000_0001_1101_0_0_0001_00000000", -- ASR:= IR, uPC:= K1
                                         -- (Direktadressering) 03
    
    b"0000_0011_1101_0_1_0001_00000000", -- ASR:= PC, PC:= PC+1, uPC:= K1
                                         -- (Immediate) 04
    
    b"0000_0001_1101_0_0_0000_00000000", -- ASR:= IR (Indirekt adressering) 05
    b"0000_0010_1101_0_0_0001_00000000", -- ASR:= PM, uPC:= K1 (indirekt)
    
    -- AR:= 0 (Indexerad adressering) 07
    b"0001_1110_0000_0_0_0000_00000000", -- AR:= IR(sign extended)
    b"0100_0111_0000_1_0_0000_00000000", -- AR:= GR7 + AR
    b"0100_0000_0000_0_0_0000_00000000",
    b"0000_0101_1101_0_0_0001_00000000", -- ASR:= AR, uPC:= K1

    -- Instruktioner
    b"0000_0010_0000_0_0_0000_00000000", -- GRx:= PM(A) (LOAD) 11
    b"0000_0010_0111_0_0_0011_00000000", -- DELAY
                                        
    b"0000_0010_0011_0_0_0011_00000000", -- PC := PM(A) (JUMP) 13
    b"0000_0111_0000_0_0_0000_00000000", -- PM(A) := GRx (STORE) 14
    b"0000_0111_0010_0_0_0011_00000000", -- DELAY

    b"0011_0000_0000_0_0_0000_00000000", -- AR := 0 (ADD) 16
    b"0100_0111_0000_0_0_0000_00000000", -- AR := 0 + GRx
    b"0100_0010_0000_0_0_0000_00000000", -- AR := AR + PM(A)
    b"0000_0101_0111_0_0_0011_00000000", -- GRx := AR

    b"0011_0000_0000_0_0_0000_00000000", -- AR := 0 (SUB) 20
    b"0100_0111_0000_0_0_0000_00000000", -- AR := 0 + GRx
    b"0101_0010_0000_0_0_0000_00000000", -- AR := AR - PM(A)
    b"0000_0101_0111_0_0_0011_00000000", -- GRx := AR

