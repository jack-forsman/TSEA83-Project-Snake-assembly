    b"0100_0011_0000_0_0_0000_00000000", -- AR := PC
    b"0100_1110_0000_0_0_0000_00000000", -- AR := AR + IR(Sign extended)
    b"0000_0101_0011_0_0_0011_00000000", -- PC := AR
    
