    b"0000_0000_0000_0_0_0000_00000000",
    b"0000_0000_0000_0_0_0000_00000000",
    others => (others => '0')
  );

 signal u_mem : u_mem_t := u_mem_c;

begin  -- Behavioral
  uData <= u_mem(to_integer(uAddr));

end Behavioral;
